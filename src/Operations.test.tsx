import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import Operations from './Operations'
const api={pending:vi.fn(),read:vi.fn(),execute:vi.fn(),finish:vi.fn()}
beforeEach(()=>{vi.clearAllMocks();Object.assign(window,{adminOperations:api});api.pending.mockResolvedValue([]);api.read.mockResolvedValue([]);api.execute.mockResolvedValue({withdrawn:true,requestId:'9007199254740993'});api.finish.mockResolvedValue(undefined)})
afterEach(cleanup)
it('submits an exact string cancellation generation and refreshes audit, eligibility and order after success',async()=>{
 render(<Operations orderId={41}/> )
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'withdrawCancellation'}})
 fireEvent.change(screen.getByLabelText('Exact cancellation request ID from audit'),{target:{value:'9007199254740993'}})
 fireEvent.change(screen.getByLabelText('Reason (at least 10 characters)'),{target:{value:'Withdraw mistaken cancellation request'}})
 fireEvent.click(screen.getByRole('checkbox'))
 fireEvent.click(screen.getByRole('button',{name:'Withdraw paid cancellation'}))
 await waitFor(()=>expect(api.execute).toHaveBeenCalledWith('withdrawCancellation',{orderId:41,requestId:'9007199254740993',reason:'Withdraw mistaken cancellation request'}))
 await waitFor(()=>expect(api.read).toHaveBeenCalledWith('audit',{orderId:41}))
 expect(api.read).toHaveBeenCalledWith('eligibility',{orderId:41})
 expect(screen.getByText('9007199254740993')).toBeTruthy()
})
it('shows version conflicts and never replaces the request ID or initiates a refund automatically',async()=>{
 api.execute.mockRejectedValueOnce(new Error('Cancellation request changed. Refresh audit history.'))
 render(<Operations orderId={41}/> )
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'withdrawCancellation'}})
 fireEvent.change(screen.getByLabelText('Exact cancellation request ID from audit'),{target:{value:'123'}})
 fireEvent.change(screen.getByLabelText('Reason (at least 10 characters)'),{target:{value:'Withdraw mistaken cancellation request'}})
 fireEvent.click(screen.getByRole('checkbox'));fireEvent.click(screen.getByRole('button',{name:'Withdraw paid cancellation'}))
 await waitFor(()=>expect(screen.getByRole('alert').textContent).toContain('Refresh audit history'))
 expect(api.execute).toHaveBeenCalledTimes(1)
 expect(screen.getByLabelText<HTMLInputElement>('Exact cancellation request ID from audit').value).toBe('123')
})
it('requires session availability and explicit confirmation for write operations',()=>{
 render(<Operations sessionBlocked orderId={41}/> )
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'stocktake'}})
 expect(screen.getByRole<HTMLButtonElement>('button',{name:'Reconcile physical stocktake'}).disabled).toBe(true)
 expect(api.execute).not.toHaveBeenCalled()
})
it('offers safe recovery of saved uncertainty and no discard button',async()=>{
 api.pending.mockResolvedValue([{operation:'withdrawCancellation',input:{orderId:41,requestId:'123',reason:'Withdraw mistaken cancellation'},key:'saved-key',state:'uncertain'}])
 render(<Operations/>)
 await waitFor(()=>expect(screen.getByText(/Saved Withdraw paid cancellation \(order Id 41\): uncertain/)).toBeTruthy())
 expect(screen.queryByRole('button',{name:'Finish saved action'})).toBeNull()
 fireEvent.click(screen.getByRole('button',{name:'Load saved intent'}))
 expect(screen.getByLabelText<HTMLInputElement>('Exact cancellation request ID from audit').value).toBe('123')
 expect(api.execute).not.toHaveBeenCalled()
})
it('More on the Way on a published product sends availability only and never isPublished', async () => {
 render(<Operations listingId={4}/>)
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'availability'}})
 fireEvent.change(screen.getByLabelText('Product ID'),{target:{value:'7'}})
 fireEvent.change(screen.getByLabelText('Availability policy'),{target:{value:'MORE_ON_THE_WAY'}})
 fireEvent.change(screen.getByLabelText(/genuine restock expectation/),{target:{value:'true'}})
 fireEvent.change(screen.getByLabelText('Definitive policy confirmation / restock expectation evidence'),{target:{value:'Supplier confirmed restock in November'}})
 fireEvent.click(screen.getByRole('checkbox'));fireEvent.click(screen.getByRole('button',{name:'Change availability policy'}))
 await waitFor(()=>expect(api.execute).toHaveBeenCalledWith('availability',{productId:7,availabilityState:'MORE_ON_THE_WAY',restockExpectationConfirmed:true,availabilityReason:'Supplier confirmed restock in November'}))
})
it('publication and availability need explicit choices; blanks send nothing and never default to unpublish or Standard', async () => {
 render(<Operations listingId={4}/>)
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'publication'}})
 fireEvent.change(screen.getByLabelText('Product ID'),{target:{value:'7'}})
 expect(screen.getByLabelText<HTMLSelectElement>('Publication').value).toBe('')
 fireEvent.click(screen.getByRole('checkbox'));fireEvent.submit(screen.getByRole('button',{name:'Publish or unpublish product'}).closest('form')!)
 await waitFor(()=>expect(screen.getByRole('alert').textContent).toContain('No request was sent'))
 expect(api.execute).not.toHaveBeenCalled()
 fireEvent.change(screen.getByLabelText('Publication'),{target:{value:'true'}})
 expect(screen.getByRole<HTMLInputElement>('checkbox').checked).toBe(false) // Any edit requires reconfirmation.
 fireEvent.click(screen.getByRole('checkbox'));fireEvent.click(screen.getByRole('button',{name:'Publish or unpublish product'}))
 await waitFor(()=>expect(api.execute).toHaveBeenCalledWith('publication',{productId:7,isPublished:true}))
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'availability'}})
 expect(screen.getByLabelText<HTMLSelectElement>('Availability policy').value).toBe('')
})
it('leaving Discontinued sends the explicit reversal confirmation only when chosen', async () => {
 render(<Operations listingId={4}/>)
 fireEvent.change(screen.getByLabelText('Workflow'),{target:{value:'availability'}})
 fireEvent.change(screen.getByLabelText('Product ID'),{target:{value:'7'}})
 fireEvent.change(screen.getByLabelText('Availability policy'),{target:{value:'STANDARD'}})
 fireEvent.change(screen.getByLabelText(/no longer permanently discontinued/),{target:{value:'true'}})
 fireEvent.change(screen.getByLabelText('Definitive policy confirmation / restock expectation evidence'),{target:{value:'Owner approved returning this product to sale'}})
 fireEvent.click(screen.getByRole('checkbox'));fireEvent.click(screen.getByRole('button',{name:'Change availability policy'}))
 await waitFor(()=>expect(api.execute).toHaveBeenCalledWith('availability',{productId:7,availabilityState:'STANDARD',discontinuationReversalConfirmed:true,availabilityReason:'Owner approved returning this product to sale'}))
})
it('offers an audited investigated outcome only for uncertain non-replayable intents', async () => {
 const resolve=vi.fn().mockResolvedValue({auditId:'9',replayed:false});Object.assign(api,{resolve})
 api.pending.mockResolvedValueOnce([{operation:'securityReview',input:{orderId:41,action:'RELEASE',note:'Mistyped order identifier'},key:'k1',state:'uncertain'},{operation:'refund',input:{orderId:42,paymentId:7,amount:5,reason:'Customer refund request'},key:'k2',state:'uncertain'}]).mockResolvedValue([])
 render(<Operations/>)
 await waitFor(()=>expect(screen.getAllByRole('button',{name:'Record investigated outcome'})).toHaveLength(1))
 fireEvent.click(screen.getByRole('button',{name:'Record investigated outcome'}))
 fireEvent.change(screen.getByLabelText('Investigated outcome'),{target:{value:'NOT_APPLIED'}})
 fireEvent.change(screen.getByLabelText('Investigation evidence (at least 10 characters)'),{target:{value:'Order audit shows no security event'}})
 fireEvent.click(screen.getByRole('button',{name:'Record outcome and clear intent'}))
 await waitFor(()=>expect(resolve).toHaveBeenCalledWith('securityReview',{orderId:41,action:'RELEASE',note:'Mistyped order identifier'},'NOT_APPLIED','Order audit shows no security event'))
 expect(api.execute).not.toHaveBeenCalled()
})
